def _lerp(lo, hi, t):
    """Two point-compatible glyphs, mixed at t (0 = lo, 1 = hi) by fontTools' variation model."""
    from fontTools.varLib.models import VariationModel
    scalars = VariationModel([{"t": 0}, {"t": 1}], axisOrder=["t"]).getMasterScalars({"t": t})
    a, b = _numbers(lo), _numbers(hi)
    return _from_numbers(lo, [scalars[0] * x + scalars[1] * y for x, y in zip(a, b)])


class InterpolateReq(FontReq):
    a: str
    b: str
    t: float = 0.5
    name: str  # the glyph that receives the result (made if missing)


@app.post("/api/interpolate")
def interpolate_glyphs(req: InterpolateReq):
    """A glyph between two others: at t = 0 it is `a`, at 1 it is `b`. They need the same contours,
    points and components, as masters do. Writes into `name`, which can't be `a` or `b`."""
    if not 0 <= req.t <= 1:
        raise HTTPException(400, "t is between 0 (the first glyph) and 1 (the second)")
    if req.name in (req.a, req.b):
        raise HTTPException(400, "the result needs its own glyph, not one of the two being mixed")
    both = _call("point_data", fid=req.fid, names=[req.a, req.b])
    missing = [n for n in (req.a, req.b) if n not in both]
    if missing:
        raise HTTPException(400, f"no glyph called {', '.join(missing)}")
    if _shape_of(both[req.a]) != _shape_of(both[req.b]):
        raise HTTPException(400, f"{req.a} and {req.b} don't match: same contours, same points, same order")
    _call("set_point_data", fid=req.fid, glyphs={req.name: _lerp(both[req.a], both[req.b], req.t)})
    return _call("points", fid=req.fid, name=req.name)


def _smart_regen(fid, name, parts):
    """Write `name`'s outline from its parts: each part's two glyphs blended at t
    (fontTools' variation model, the same maths as a variable font), then moved
    and joined. Anchors stay; components are replaced."""
    from smart_components import compose, max_name
    items = []
    for p in parts:
        both = _call("point_data", fid=fid, names=[p["part"], max_name(p["part"])])
        lo, hi = both[p["part"]], both[max_name(p["part"])]
        if _shape_of(lo) != _shape_of(hi):
            raise HTTPException(400, f"{p['part']} and {max_name(p['part'])} don't match: same contours, same points, same order")
        items.append((_lerp(lo, hi, p["t"]), p["dx"], p["dy"]))
    own = _call("point_data", fid=fid, names=[name])[name]
    out = compose(items) if items else {"width": own["width"], "contours": [], "closed": []}
    _call("set_point_data", fid=fid, glyphs={name: {**out, "refs": [], "anchors": own["anchors"]}})
    return _call("points", fid=fid, name=name)


@app.get("/api/smart")
def smart(fid: int):
    return _call("smart", fid=fid)


@app.post("/api/smart/set")
def smart_set(req: SmartReq):
    """Build a glyph from parts (or, with no parts, stop; the outline stays as drawn)."""
    old = _call("smart", fid=req.fid, names=[req.name])["glyphs"].get(req.name, [])
    stored = _call("set_smart", fid=req.fid, name=req.name, parts=[p.model_dump() for p in req.parts])["parts"]
    try:
        return _smart_regen(req.fid, req.name, stored) if stored else _call("points", fid=req.fid, name=req.name)
    except HTTPException:
        _call("set_smart", fid=req.fid, name=req.name, parts=old)  # a refused change leaves the glyph as it was
        raise


@app.post("/api/smart/apply")
def smart_apply(req: FontReq):
    """Rebuild every glyph that has parts (after a part changed); returns their names."""
    built = _call("smart", fid=req.fid)["glyphs"]
    for name, parts in built.items():
        _smart_regen(req.fid, name, parts)
    return {"rebuilt": sorted(built)}
