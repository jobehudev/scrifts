# ------------------------------------------------------ glyph database
#
# What a code point is (name, category, script, block, decomposition) comes
# from Python's unicodedata and fontTools' Unicode data; the glyph names are
# FontForge's. Nothing here is a hand-kept table except which blocks to offer.

GLYPH_BLOCKS = [
    ("basic-latin", "Basic Latin", 0x20, 0x7E, "Latin"),
    ("latin-1", "Latin-1 Supplement", 0xA0, 0xFF, "Latin"),
    ("latin-ext-a", "Latin Extended-A", 0x100, 0x17F, "Latin"),
    ("latin-ext-b", "Latin Extended-B", 0x180, 0x24F, "Latin"),
    ("latin-ext-additional", "Latin Extended Additional", 0x1E00, 0x1EFF, "Latin"),
    ("greek", "Greek and Coptic", 0x370, 0x3FF, "Greek"),
    ("cyrillic", "Cyrillic", 0x400, 0x4FF, "Cyrillic"),
    ("punctuation", "General Punctuation", 0x2000, 0x206F, "Symbols"),
    ("currency", "Currency Symbols", 0x20A0, 0x20CF, "Symbols"),
    ("arrows", "Arrows", 0x2190, 0x21FF, "Symbols"),
    ("math", "Mathematical Operators", 0x2200, 0x22FF, "Symbols"),
]


CATEGORIES = {"Lu": "Uppercase letter", "Ll": "Lowercase letter", "Lt": "Titlecase letter", "Lm": "Modifier letter", "Lo": "Other letter",
              "Mn": "Combining mark", "Mc": "Spacing mark", "Me": "Enclosing mark", "Nd": "Decimal digit", "Nl": "Letter number",
              "No": "Other number", "Pc": "Connector punctuation", "Pd": "Dash", "Ps": "Opening bracket", "Pe": "Closing bracket",
              "Pi": "Initial quote", "Pf": "Final quote", "Po": "Other punctuation", "Sm": "Math symbol", "Sc": "Currency symbol",
              "Sk": "Modifier symbol", "So": "Other symbol", "Zs": "Space", "Zl": "Line separator", "Zp": "Paragraph separator",
              "Cc": "Control", "Cf": "Format", "Cs": "Surrogate", "Co": "Private use", "Cn": "Unassigned"}


def _assigned(cp):
    import unicodedata
    return unicodedata.category(chr(cp)) not in ("Cn", "Cc", "Cs", "Co")


@app.get("/api/glyphdb/info")
def glyphdb_info(unicode: int):
    """What a code point is, for the glyph panel."""
    import unicodedata
    from fontTools import unicodedata as fu
    if not 0 <= unicode <= 0x10FFFF:
        raise HTTPException(400, "not a Unicode code point")
    ch = chr(unicode)
    cat = unicodedata.category(ch)
    dec = unicodedata.decomposition(ch)
    return {
        "unicode": unicode, "name": unicodedata.name(ch, ""), "category": cat, "category_name": CATEGORIES.get(cat, cat),
        "script": fu.script_name(fu.script(ch)), "block": fu.block(ch),
        # a canonical decomposition lists its parts (é = e + acute); <compat> ones are formatting variants
        "decomposition": [int(x, 16) for x in dec.split() if not x.startswith("<")] if dec and not dec.startswith("<") else [],
        "uppercase": ord(ch.upper()) if len(ch.upper()) == 1 and ch.upper() != ch else None,
        "lowercase": ord(ch.lower()) if len(ch.lower()) == 1 and ch.lower() != ch else None,
    }


def _have_codepoints(fid):
    return set(_call("codepoints", fid=fid))


@app.get("/api/glyphdb/blocks")
def glyphdb_blocks(fid: int):
    """The blocks the font could cover, with how many of their characters it has."""
    have = _have_codepoints(fid)
    out = []
    for bid, name, lo, hi, group in GLYPH_BLOCKS:
        cps = [c for c in range(lo, hi + 1) if _assigned(c)]
        out.append({"id": bid, "name": name, "group": group, "total": len(cps), "have": sum(c in have for c in cps)})
    return out


class AddGlyphsReq(FontReq):
    blocks: list[str]


@app.post("/api/glyphdb/add")
def glyphdb_add(req: AddGlyphsReq):
    """Empty glyphs for every assigned character of these blocks that the font doesn't have."""
    chosen = [b for b in GLYPH_BLOCKS if b[0] in req.blocks]
    if len(chosen) != len(set(req.blocks)):
        raise HTTPException(400, "unknown block: " + ", ".join(sorted(set(req.blocks) - {b[0] for b in GLYPH_BLOCKS})))
    have = _have_codepoints(req.fid)
    todo = [c for _, _, lo, hi, _ in chosen for c in range(lo, hi + 1) if _assigned(c) and c not in have]
    return _call("create_many", fid=req.fid, codepoints=todo)


