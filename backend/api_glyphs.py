@app.post("/api/shape")
def shape(req: ShapeReq):
    """Shape text with HarfBuzz using the font as it is now (compiled by
    FontForge into a temporary file). Glyph names and positions."""
    import uharfbuzz as hb

    import io

    key = (req.fid, _shape["rev"])
    if _shape["key"] != key:  # compiled once per change to the font, not once per letter typed in the preview
        path = _call("webfont", fid=req.fid)["path"]
        try:
            _shape["font"], _shape["key"] = Path(path).read_bytes(), key  # in memory: Windows won't delete a file still mapped
        finally:
            Path(path).unlink(missing_ok=True)
    data = _shape["font"]
    order = TTFont(io.BytesIO(data), lazy=True).getGlyphOrder()
    font = hb.Font(hb.Face(hb.Blob(data)))
    buf = hb.Buffer()
    buf.add_str(req.text[:500])
    buf.guess_segment_properties()
    hb.shape(font, buf, req.features)
    return [{"name": order[i.codepoint], "cluster": i.cluster, "ax": p.x_advance, "dx": p.x_offset, "dy": p.y_offset}
            for i, p in zip(buf.glyph_infos, buf.glyph_positions)]


@app.get("/api/webfont")
def webfont(fid: int):
    """The open font as a web font, generated by FontForge, for showing the UI in it."""
    path = _call("webfont", fid=fid)["path"]
    try:
        data = Path(path).read_bytes()
    finally:
        Path(path).unlink(missing_ok=True)
    kind = "font/ttf" if path.endswith(".ttf") else "font/otf"
    return Response(data, media_type=kind, headers={"Cache-Control": "no-store"})


def _is_default(v, location):
    return not v or not location or all(
        abs(location.get(a["tag"], a["default"]) - a["default"]) < 1e-6 for a in v.axes)


